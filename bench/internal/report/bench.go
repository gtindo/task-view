// Latest keeps the newest result of each run, in first-seen order. A
// resumed run appends a retry after its failure, and only the retry counts.
func Latest(results []metrics.Result) []metrics.Result {
	position := map[string]int{}
	var latest []metrics.Result
	for _, result := range results {
		if index, seen := position[result.RunID]; seen {
			latest[index] = result

			continue
		}

		position[result.RunID] = len(latest)
		latest = append(latest, result)
	}

	return latest
}

// ApplySizes labels each result with its case's size from the suite, so a
// case moved to another size class after its runs is reported under the
// new one. Results of cases the suite no longer lists keep their size.
func ApplySizes(results []metrics.Result, suite config.Suite) []metrics.Result {
	sizes := map[string]string{}
	for _, task := range suite.Cases {
		sizes[task.ID] = task.Size
	}

	labelled := slices.Clone(results)
	for i, result := range labelled {
		if size, ok := sizes[result.Case]; ok {
			labelled[i].Size = size
		}
	}

	return labelled
}

// inMatrixOrder sorts cells by size and case, then by the matrix's own model
// and effort order, which runs from cheapest to most capable rather than
// alphabetically. Models or efforts the matrix does not list sort last.
func inMatrixOrder(cells []Cell, matrix config.Matrix) []Cell {
	rank := func(list []string, value string) int {
		if index := slices.Index(list, value); index >= 0 {
			return index
		}

		return len(list)
	}

	modelIDs := make([]string, 0, len(matrix.Models))
	for _, model := range matrix.Models {
		modelIDs = append(modelIDs, model.ID)
	}

	ordered := slices.Clone(cells)
	slices.SortStableFunc(ordered, func(left, right Cell) int {
		if bySize := rank(config.Sizes, left.Size) - rank(config.Sizes, right.Size); bySize != 0 {
			return bySize
		}

		if byCase := strings.Compare(left.Case, right.Case); byCase != 0 {
			return byCase
		}

		if byModel := rank(modelIDs, left.Model) - rank(modelIDs, right.Model); byModel != 0 {
			return byModel
		}

		return rank(matrix.Efforts, left.Effort) - rank(matrix.Efforts, right.Effort)
	})

	return ordered
}

// minAgreement is the node agreement a setting needs to be recommended. A
// review can validate while mapping each file as one node with no edges;
// repeats of such shallow maps disagree, so agreement screens them out.
const minAgreement = 0.5

// sizeMeanings says what kind of change each size class stands for.
var sizeMeanings = map[string]string{
	"small":       "a focused fix in a couple of files",
	"medium":      "a feature or refactor across a few files",
	"big":         "a large pull request across many files",
	"agent-scale": "beyond what a person writes by hand in one sitting: thousands of lines produced with agents in a short time",
}

// Bench is what BENCH.md is rendered from: one published results folder.
// Results holds the latest result of each run, Archive the archive's path
// relative to the repo root and Dashboard, when set, the link to the same
// results drawn as charts.
type Bench struct {
	Meta      Meta
	Suite     config.Suite
	Results   []metrics.Result
	Cells     []Cell
	Archive   string
	Dashboard string
}

// dateLength is the YYYY-MM-DD prefix of an RFC 3339 timestamp.
const dateLength = len("2006-01-02")

// BenchMarkdown renders BENCH.md: what was run and at what prices, how to
// choose a model by change size, then every table down to single cells,
// and where the archived reviews and pages are.
func BenchMarkdown(bench Bench) string {
	bench.Cells = inMatrixOrder(bench.Cells, bench.Meta.Matrix)

	var out strings.Builder
	out.WriteString("# task-view benchmark\n\n")
	out.WriteString("What does writing a task-view review cost, for a change of a given size, on a given model and effort, and does the review match the diff? ")
	out.WriteString("Each run hands an agent a finished task and its brief and asks for a review file; the runner then validates it with the same task-view binary. ")
	out.WriteString("How the cases were picked, how to rerun it and its known biases are in [bench/README.md](bench/README.md). ")
	out.WriteString("This file is generated by `make bench-publish` and holds the latest run only.\n\n")
	if bench.Dashboard != "" {
		fmt.Fprintf(&out, "The same results as charts: [task-view benchmark dashboard](%s).\n\n", bench.Dashboard)
	}

	writeRunSection(&out, bench)
	writePriceSection(&out, bench.Meta)
	writeChoiceSection(&out, bench.Suite, bench.Results, bench.Cells)

	out.WriteString("## By model and effort, all cases\n\n")
	writeModelTable(&out, summarize(bench.Cells, nil))

	writeTokenSection(&out, bench.Suite, bench.Cells)

	writeCaseSection(&out, bench.Suite, bench.Results)

	out.WriteString("\n## Every cell\n\n")
	writeCellTable(&out, bench.Cells)

	writeArchiveSection(&out, bench.Archive)
	writeDefinitions(&out)

	return out.String()
}

func writeRunSection(out *strings.Builder, bench Bench) {
	meta := bench.Meta
	failed := 0
	var dates []string
	for _, result := range bench.Results {
		if result.HarnessError != "" || result.TimedOut {
			failed++
		}

		if len(result.StartedAt) >= dateLength {
			dates = append(dates, result.StartedAt[:dateLength])
		}
	}

	when := "unknown"
	if len(dates) > 0 {
		when = slices.Min(dates)
		if last := slices.Max(dates); last != when {
			when += " to " + last
		}
	}

	harness := "`" + meta.Harness + "`"
	if meta.HarnessVersion != "" {
		harness += " (`" + meta.HarnessVersion + "`)"
	}

	models := make([]string, 0, len(meta.Matrix.Models))
	for _, model := range meta.Matrix.Models {
		models = append(models, fmt.Sprintf("%s (`%s`)", model.Label, model.ID))
	}

	out.WriteString("## This run\n\n")
	fmt.Fprintf(out, "- Date: %s\n", when)
	fmt.Fprintf(out, "- task-view: `%s`\n", meta.TaskView)
	fmt.Fprintf(out, "- Harness: %s on %s\n", harness, meta.OS)
	fmt.Fprintf(out, "- Models: %s\n", strings.Join(models, ", "))
	fmt.Fprintf(out, "- Efforts: %s; %d %s per cell; time limit %s per run\n",
		strings.Join(meta.Matrix.Efforts, ", "), meta.Matrix.Repeats, plural(meta.Matrix.Repeats, "repeat", "repeats"), meta.Matrix.Timeout)
	fmt.Fprintf(out, "- Runs: %d over %d cases, %d failed (harness error or time limit)\n\n",
		len(bench.Results), len(bench.Suite.Cases), failed)
}

func writePriceSection(out *strings.Builder, meta Meta) {
	prices := meta.PriceList
	out.WriteString("## API prices at the time\n\n")
	fmt.Fprintf(out, "Prices as of %s, in US$ per million tokens. %s\n\n", prices.AsOf, prices.Source)
	out.WriteString("| Model | Input | Output | Cache read | Cache write |\n")
	out.WriteString("| --- | --- | --- | --- | --- |\n")
	for _, model := range meta.Matrix.Models {
		price, ok := prices.Models[model.Price]
		if !ok {
			fmt.Fprintf(out, "| %s | – | – | – | – |\n", model.Label)

			continue
		}

		fmt.Fprintf(out, "| %s | %s | %s | %s | %s |\n",
			model.Label, dollars(price.Input), dollars(price.Output), dollars(price.CacheRead), dollars(price.CacheWrite))
	}

	out.WriteString("\nCosts below are the harness's own figure for each session where it reports one (Claude Code does), else tokens times these prices, marked \"computed\". ")
	out.WriteString("Claude Code reports the API-equivalent cost even when it runs on a subscription, so the figures are what the same sessions would cost on the API at these prices.\n\n")
}

func dollars(value float64) string {
	return strings.TrimRight(strings.TrimRight(fmt.Sprintf("%.3f", value), "0"), ".")
}

func writeChoiceSection(out *strings.Builder, suite config.Suite, results []metrics.Result, cells []Cell) {
	rows := summarize(cells, func(cell Cell) string { return cell.Size })
	out.WriteString("## Choosing a model\n\n")
	out.WriteString("Sizes are judged on the whole task's changed lines (added plus removed):\n\n")
	writeSizeLegend(out, suite, results)
	fmt.Fprintf(out, "\nPer change size, the cheapest setting whose every run produced an accurate review and whose repeats drew a consistent map (node agreement at least %.1f):\n\n", minAgreement)
	out.WriteString("| Size | Cheapest accurate, consistent setting | Mean cost per run (US$) | Mean minutes per run | Node agreement |\n")
	out.WriteString("| --- | --- | --- | --- | --- |\n")
	for _, size := range config.Sizes {
		sized := slices.DeleteFunc(slices.Clone(rows), func(row summaryRow) bool { return row.group != size })
		if len(sized) == 0 {
			continue
		}

		recommendable := slices.DeleteFunc(slices.Clone(sized), func(row summaryRow) bool {
			return row.accurate < row.runs || row.agreement < minAgreement
		})
		if len(recommendable) == 0 {
			best := slices.MaxFunc(sized, func(left, right summaryRow) int { return left.accurate*right.runs - right.accurate*left.runs })
			fmt.Fprintf(out, "| %s | none; best is %s %s at %d/%d accurate | %.3f | %.1f | %.2f |\n",
				size, best.label, best.effort, best.accurate, best.runs, best.cost, best.minutes, best.agreement)

			continue
		}

		cheapest := slices.MinFunc(recommendable, func(left, right summaryRow) int { return compareFloats(left.cost, right.cost) })
		fmt.Fprintf(out, "| %s | %s, %s effort | %.3f | %.1f | %.2f |\n",
			size, cheapest.label, cheapest.effort, cheapest.cost, cheapest.minutes, cheapest.agreement)
	}

	out.WriteString("\nNode agreement measures how consistent the maps are across repeats, not whether they are right: every accurate run covers the whole diff. See [Reading the numbers](#reading-the-numbers).\n")

	out.WriteString("\nEvery model and effort by change size:\n\n")
	out.WriteString("| Size | Model | Effort | Runs | Accurate | First validate passed | Mean nodes per review | Mean edges per review | Mean cost per run (US$) | Cost range (US$) | US$ per 100 lines | Mean minutes per run | Node agreement |\n")
	out.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
	for _, row := range rows {
		fmt.Fprintf(out, "| %s | %s | %s | %d | %d/%d | %d/%d | %.0f | %.0f | %.3f | %.3f–%.3f | %.3f | %.1f | %.2f |\n",
			row.group, row.label, row.effort, row.runs, row.accurate, row.runs, row.firstPass, row.runs,
			row.nodes, row.edges, row.cost, row.costMin, row.costMax, row.costPer100Lines, row.minutes, row.agreement)
	}

	out.WriteString("\n")
}

// writeSizeLegend lists each size class with what it stands for, its
// cases and their range of changed lines.
func writeSizeLegend(out *strings.Builder, suite config.Suite, results []metrics.Result) {
	lines := map[string]int{}
	for _, result := range results {
		lines[result.Case] = max(lines[result.Case], result.Change.Lines())
	}

	for _, size := range config.Sizes {
		var caseIDs []string
		var caseLines []int
		for _, task := range suite.Cases {
			if task.Size != size {
				continue
			}

			caseIDs = append(caseIDs, task.ID)
			if measured := lines[task.ID]; measured > 0 {
				caseLines = append(caseLines, measured)
			}
		}

		if len(caseIDs) == 0 {
			continue
		}

		cases := strings.Join(caseIDs, ", ")
		switch {
		case len(caseLines) == 0:
		case slices.Min(caseLines) == slices.Max(caseLines):
			cases += fmt.Sprintf("; %d lines", caseLines[0])
		default:
			cases += fmt.Sprintf("; %d–%d lines", slices.Min(caseLines), slices.Max(caseLines))
		}

		fmt.Fprintf(out, "- **%s**: %s (%s)\n", size, sizeMeanings[size], cases)
	}
}

// writeTokenSection lists tokens per run for each project, model and
// effort, projects in the suite's order: how much each model reads and
// writes on the same codebases.
func writeTokenSection(out *strings.Builder, suite config.Suite, cells []Cell) {
	out.WriteString("\n## Tokens by project\n\n")
	out.WriteString("Mean tokens per run over each project's cases. The total counts input, output and cache reads and writes; most of it is context read again from cache on each turn, billed at a small fraction of the input price, so the model that uses the most tokens is not the one that costs the most.\n\n")
	out.WriteString("| Project | Model | Effort | Runs | Mean tokens per run (M) | Mean output tokens per run (k) | Mean cost per run (US$) |\n")
	out.WriteString("| --- | --- | --- | --- | --- | --- | --- |\n")

	projectRank := func(id string) int {
		return slices.IndexFunc(suite.Projects, func(project config.Project) bool { return project.ID == id })
	}

	byProject := slices.Clone(cells)
	slices.SortStableFunc(byProject, func(left, right Cell) int { return projectRank(left.Project) - projectRank(right.Project) })
	for _, row := range summarize(byProject, func(cell Cell) string { return cell.Project }) {
		fmt.Fprintf(out, "| %s | %s | %s | %d | %.2f | %.1f | %.3f |\n",
			row.group, row.label, row.effort, row.runs, row.tokens*1e-6, row.output*1e-3, row.cost)
	}
}

func compareFloats(left, right float64) int {
	switch {
	case left < right:
		return -1
	case left > right:
		return 1
	}

	return 0
}

func writeCaseSection(out *strings.Builder, suite config.Suite, results []metrics.Result) {
	changes := map[string]metrics.Change{}
	for _, result := range results {
		if result.Change.Lines() > changes[result.Case].Lines() {
			changes[result.Case] = result.Change
		}
	}

	out.WriteString("\n## The cases\n\n")
	out.WriteString("| Case | Size | Language | Commits | Files | Changed lines | The task |\n")
	out.WriteString("| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, task := range suite.Cases {
		project, _ := suite.Project(task.Project)
		change := changes[task.ID]
		fmt.Fprintf(out, "| [%s](bench/briefs/%s.md) | %s | %s | %d | %d | %d | [%s](%s) |\n",
			task.ID, task.ID, task.Size, project.Language, len(task.Commits), change.Files, change.Lines(), task.Title, task.Source)
	}
}

func writeArchiveSection(out *strings.Builder, archive string) {
	out.WriteString("\n## The reviews and their pages\n\n")
	fmt.Fprintf(out, "[`%s`](%s) holds every run's output, one folder per run id (`<case>__<model>__<effort>__<repeat>`):\n\n", archive, archive)
	out.WriteString("- `change-<case>.json`: the review file the agent wrote\n")
	out.WriteString("- `review.html`: the page `task-view open` rendered from it, one offline file\n")
	out.WriteString("- `validate.json`: the final `task-view validate --format json`\n\n")
	out.WriteString("```bash\n")
	fmt.Fprintf(out, "tar -xJf %s\n", archive)
	out.WriteString("```\n\n")
	out.WriteString("Next to it, `runs.jsonl` has one result per run, `summary.csv` one row per cell and `meta.json` the settings above.\n")
}

func writeDefinitions(out *strings.Builder) {
	out.WriteString("\n## Reading the numbers\n\n")
	out.WriteString("- **Accurate:** the final review validates with exit 0 and no unmentioned hunk, and the agent changed nothing but the review file.\n")
	out.WriteString("- **First validate passed:** the agent's first `validate` already exited 0.\n")
	out.WriteString("- **Nodes and edges:** how many pieces the review's map has and how many relations link them. An accurate review can still be coarse: a node per whole file covers every hunk with little structure, which shows here and as low node agreement.\n")
	out.WriteString("- **Cost and minutes:** per run, a mean over the cell's repeats with its range.\n")
	out.WriteString("- **US$ per 100 lines:** cost against the change's added and removed lines.\n")
	out.WriteString("- **Node and edge agreement:** a consistency metric across runs. For each case and setting, it is the mean pairwise overlap (Jaccard) of the code ranges the repeats mark as changed nodes, and of their edges; 1 means every repeat drew the same map.\n")
	out.WriteString("\nEvery run still includes the full diff: a review counts as accurate only when it accounts for every hunk. ")
	out.WriteString("LLM output is not deterministic, so repeats of the same task can map that diff with more or less detail: one splits a file into functions, another keeps it whole. ")
	out.WriteString("Low agreement means the maps differ in granularity, not that changes are missing. ")
	out.WriteString("The map's accuracy also depends on the task prompt, flows above all: a flow describes how the change works end to end, so it can only be as precise as what the agent was told about the task. ")
	out.WriteString("Every run here gets the same fixed brief.\n")
}

func plural(count int, one, many string) string {
	if count == 1 {
		return one
	}

	return many
}
